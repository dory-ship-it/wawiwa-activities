// Writes lesson-art.css: the lesson's line drawings (templates/art.js) as CSS mask images, for the screens drawn by
// kit templates (explorer tiles, sort piles, decision options), where the lesson cannot add markup.
// A mask takes the colour of the element's background, so one drawing serves every category colour.
// Usage: node tests/art-css.mjs  (then npm run stamp). The output is appended to lesson.css between markers.
import { readFileSync, writeFileSync } from 'node:fs';
const src = readFileSync(new URL('../templates/art.js', import.meta.url), 'utf8');
const P = {};
for (const m of src.matchAll(/^\s+(\w+): '(.+)',$/gm)) P[m[1]] = m[2];
const uri = (name, w = 1.75) => `url("data:image/svg+xml,${encodeURIComponent(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 24 24' fill='none' stroke='black' stroke-width='${w}' stroke-linecap='round' stroke-linejoin='round'>${P[name].replace(/currentColor/g, 'black')}</svg>`)}")`;
const lines = ['/* >>> lesson art masks (generated by tests/art-css.mjs; do not edit by hand) >>> */'];
lines.push(':root {', ...Object.keys(P).map((name) => `  --m-art-${name}: ${uri(name)};`), '}');
lines.push('/* <<< lesson art masks <<< */');
const css = readFileSync(new URL('../lesson.css', import.meta.url), 'utf8').replace(/\n?\/\* >>> lesson art masks[\s\S]*?<<< lesson art masks <<< \*\/\n?/, '\n');
writeFileSync(new URL('../lesson.css', import.meta.url), css.trimEnd() + '\n\n' + lines.join('\n') + '\n');
console.log('art-css:', Object.keys(P).length, 'masks');
