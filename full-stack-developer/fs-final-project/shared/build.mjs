// Builds a Day page from its strings: node shared/build.mjs day-3 [lang]
// Writes day-N/index.html (en) or day-N/index.<lang>.html. The page is static HTML, so it reads
// without JavaScript; shared/fp.js only adds navigation, the overlays and the fit to the Rise frame.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const [day, lang = "en"] = process.argv.slice(2);
if (!day) { console.error("usage: node shared/build.mjs <day-folder> [lang]"); process.exit(1); }

const load = (file, key) => { const sb = { window: {} }; vm.runInNewContext(readFileSync(file, "utf8"), sb); return sb.window[key]; };
const S = load(join(here, `strings.${lang}.js`), "FP_SHARED");
const D = load(join(here, "..", day, `strings.${lang}.js`), "FP_DAY");
const U = S.ui;

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);
// `code` in a string becomes inline code; everything else is escaped text.
const rich = (s) => esc(s).replace(/`([^`]+)`/g, '<code>$1</code>');
const pad = (n) => String(n).padStart(2, "0");

const icon = {
  rules: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><path d="M12 3l7 3v6c0 4.5-3 7.5-7 9-4-1.5-7-4.5-7-9V6z"/><path d="M9 12l2 2 4-4"/></svg>',
  map: '<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><rect x="4" y="4" width="6" height="6" rx="1"/><rect x="14" y="4" width="6" height="6" rx="1"/><rect x="4" y="14" width="6" height="6" rx="1"/><rect x="14" y="14" width="6" height="6" rx="1"/></svg>'
};

const rows = (list) => '<ol class="rows">' + list.map((r, k) =>
  `<li><span class="n" aria-hidden="true">${pad(k + 1)}</span><span class="row-text">${rich(r)}</span></li>`).join("") + "</ol>";

const adds = (a, id, level) =>
  `<section class="adds" aria-labelledby="${id}"><h${level} class="adds-h" id="${id}">${esc(a.heading)}</h${level}>` +
  (a.lines ? `<p>${a.lines.map(rich).join("<br>")}</p>` : "") +
  `<ul>${a.list.map((x) => `<li>${rich(x)}</li>`).join("")}</ul></section>`;

const heading = (s) => `${s.step} ${s.title}`;

const screen = (s, i) => {
  const next = D.screens[i + 1];
  const cta = next ? heading(next) : D.finalCta;
  let h = `<section class="screen" id="s-${s.id}" aria-labelledby="h-${s.id}" data-cta="${esc(cta)}"><div class="inner">`;
  h += `<h1 class="title" id="h-${s.id}" tabindex="-1"><span class="t-step">${esc(s.step)}</span> <span class="t-main">${esc(s.title)}</span></h1>`;
  if (s.create) {
    h += `<p class="create"><span class="create-tag">${esc(s.create.label)}</span> <code class="path">${esc(s.create.path)}</code> ` +
      `<button class="tbtn copy" type="button" data-copy="${esc(s.create.path)}" data-done="${esc(U.copied)}"><span class="copy-lbl">${esc(U.copy)}</span></button></p>`;
  }
  s.sections.forEach((sec, k) => {
    const id = `l-${s.id}-${k}`;
    h += sec.heading ? `<h2 class="label" id="${id}">${esc(sec.heading)}</h2>` : `<p class="label" id="${id}">${esc(sec.label)}</p>`;
    h += rows(sec.rows).replace('<ol class="rows">', `<ol class="rows" aria-labelledby="${id}">`);
  });
  if (s.additions) h += adds(s.additions, `a-${s.id}`, 2);
  return h + "</div></section>";
};

const html = `<!doctype html>
<html lang="${S.lang}" dir="${S.dir}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(D.docTitle)}</title>
<meta name="description" content="${esc(D.docTitle)}">
<!-- Generated by shared/build.mjs from strings.${lang}.js. Edit the strings, then rebuild. -->
<link rel="preload" href="../shared/fonts/assistant-latin-800-normal.woff2" as="font" type="font/woff2" crossorigin>
<link rel="preload" href="../shared/fonts/assistant-latin-400-normal.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="../shared/fp.css">
<script>document.documentElement.classList.add("js")</script>
</head>
<body>
<div class="canvas">
<header class="top">
<img class="logo" src="../shared/wawiwa-logo.png" alt="${esc(U.logoAlt)}" width="92" height="39">
<span class="day">${esc(D.day)}</span>
<div class="prog" aria-hidden="true">${D.screens.map(() => "<i></i>").join("")}</div>
<button class="tbtn" type="button" data-open="rules" aria-haspopup="dialog">${icon.rules}<span>${esc(U.rules)}</span></button>
<button class="tbtn" type="button" data-open="map" aria-haspopup="dialog">${icon.map}<span>${esc(U.map)}</span></button>
</header>
<main class="stage" id="stage">
${D.screens.map(screen).join("\n")}
</main>
<footer class="bottom">
<button class="ghost" type="button" id="backBtn">${esc(U.back)}</button>
<span class="hint" aria-hidden="true"><kbd>←</kbd><kbd>→</kbd></span>
<button class="cta" type="button" id="ctaBtn">${esc(heading(D.screens[1] || D.screens[0]))}</button>
</footer>
</div>
<dialog class="sheet" id="rules" aria-labelledby="rules-h" open>
<div class="sheet-inner">
<div class="sheet-head"><h2 id="rules-h">${esc(S.rules.title)}</h2><button class="tbtn" type="button" data-close>${esc(U.close)}</button></div>
${rows(S.rules.rows)}
${adds(S.rules.additions, "rules-a", 3)}
</div>
</dialog>
<dialog class="sheet" id="map" aria-labelledby="map-h" open>
<div class="sheet-inner">
<div class="sheet-head"><h2 id="map-h">${esc(U.map)}</h2><button class="tbtn" type="button" data-close>${esc(U.close)}</button></div>
<ol class="map-list">${D.screens.map((s, i) => `<li><button type="button" data-go="${i}"><span class="n" aria-hidden="true">${pad(i + 1)}</span><span class="m-step">${esc(s.step)}</span><span class="m-title">${esc(s.title)}</span></button></li>`).join("")}</ol>
</div>
</dialog>
<p class="sr-only" aria-live="polite" id="live"></p>
<span class="end" id="end" aria-hidden="true"></span>
<script src="../shared/fp.js"></script>
</body>
</html>
`;

const out = join(here, "..", day, lang === "en" ? "index.html" : `index.${lang}.html`);
writeFileSync(out, html);
console.log("wrote " + out);
